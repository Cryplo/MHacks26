import { Link, useParams } from 'react-router-dom';
import { useRunManifestAndPark } from '../../data/hooks';
import { useAsync } from '../../data/useAsync';
import { METRICS, METRIC_ORDER } from '../../domain/metrics';
import { displayModes } from '../../runtime/mode';
import { useRuntime } from '../../runtime/RuntimeProvider';
import { ErrorBox, ModeBadges, Spinner } from '../../ui/components';
import { formatDuration, formatEpoch, formatMetric, formatPercent, formatSimClock } from '../../ui/format';
import { describeChange, eventTime } from '../scenarios/describe';
import { resultQualityLabel } from './ResultsPage';

/** One-page executive summary for browser print ("Save as PDF" is the browser's feature). */
export function PrintPage() {
  const { runId = '' } = useParams();
  const rt = useRuntime();
  const base = useRunManifestAndPark(runId);
  const snap = useAsync(() => rt.client.query('getLiveSnapshot', { runId }), [rt.client, runId]);
  if (base.error) return <ErrorBox error={base.error} />;
  if (snap.error) return <ErrorBox error={snap.error} />;
  if (!base.data || !snap.data) return <Spinner label="Preparing printable summary…" />;
  const { manifest, park } = base.data;
  const { run, metrics } = snap.data;
  const modes = displayModes({ profile: rt.settings.profile, run, quality: run.quality });
  const q = resultQualityLabel(run);
  const caveats = [
    ...(rt.settings.profile === 'fixture' ? ['FIXTURE: scripted data for UI development; no simulation or Jev was involved.'] : []),
    ...(run.mode === 'mock' ? ['MOCK provider: not a real-Jev comparison.'] : []),
    'Synthetic guests and park; the model is not calibrated to real visitors.',
    'Satisfaction is a synthetic rating, not a human survey; missing ratings are not imputed.',
    'Single run: an illustration, not an experiment. Use paired seeds for comparisons.',
    ...run.quality.reasons,
  ];
  return (
    <article className="stack" data-testid="print-page" style={{ maxWidth: 900 }}>
      <div className="row no-print">
        <button type="button" className="btn primary" onClick={() => window.print()}>Print / save as PDF (browser print dialog)</button>
        <Link className="btn" to={`/runs/${encodeURIComponent(runId)}/results`}>Back to results</Link>
        <span className="small muted">This page is formatted for one printed page. No PDF is generated by this app.</span>
      </div>
      <header>
        <h1>Harbor Lights — run summary</h1>
        <div className="row"><ModeBadges modes={modes} /><span className="badge neutral">{q.label}</span></div>
        <p className="small">Run <span className="mono">{run.runId}</span> · generated {formatEpoch(Date.now())} · source profile {rt.settings.profile} · results as of {formatSimClock(run.simMs, park.openLocal)}</p>
      </header>
      <section>
        <h3>What was run</h3>
        <p className="small">Scenario <b>{manifest.scenario.label}</b>: {manifest.scenario.events.length ? manifest.scenario.events.map((e) => `${describeChange(e.change, park, false).operation} (${describeChange(e.change, park, false).value}) at ${eventTime(e, park)}`).join('; ') : 'no changes (baseline)'}. Seed <span className="mono">{manifest.replicateSeed}</span>; horizon {formatDuration(manifest.config.horizonMs)} from {park.openLocal}; {metrics.admittedGuests} admitted guests. Satisfaction coverage {formatPercent(metrics.measures.satisfaction_0_100.coverage, 0)}.</p>
      </section>
      <section>
        <h3>Key measures (units as shown)</h3>
        <table className="small">
          <thead><tr><th>Measure</th><th className="num">Value</th><th>Definition</th></tr></thead>
          <tbody>{METRIC_ORDER.slice(0, 9).map((id) => <tr key={id}><td>{METRICS[id].label}</td><td className="num">{formatMetric(metrics.measures[id])}{metrics.measures[id].complete ? '' : ' (partial)'}</td><td className="muted">{METRICS[id].definition}</td></tr>)}</tbody>
        </table>
      </section>
      <section>
        <h3>Caveats</h3>
        <ul className="small" data-testid="print-caveats">{caveats.map((c) => <li key={c}>{c}</li>)}</ul>
      </section>
    </article>
  );
}
